function Locale.t(key, language, ...)
    local value = language == "es" and key or (english[key] or key)
    if select("#", ...) > 0 then return string.format(value, ...) end
    return value
end

function Locale.decimal(value, language)
    return language == "es" and value:gsub("%.", ",") or value
end

function Locale.known(key)
    return english[key] ~= nil
end

return Locale
