local Icons = {}
local artwork_palette = require("mhoverlay/artwork")
local alphabet = "0123456789ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz-_"
local colored_sprites = {}

local function colored_sprite(name)
    if colored_sprites[name] then return colored_sprites[name] end
    local source = assert(artwork_palette[name], "Unknown artwork: " .. tostring(name))
    local colors = {}
    for index = 1, #source.palette do colors[alphabet:sub(index, index)] = source.palette[index] end
    local spans, previous = {}, {}
    assert(#source.rows == 64, "Invalid artwork height: " .. name)
    for y, row in ipairs(source.rows) do
        assert(#row == 64, "Invalid artwork width: " .. name)
        local current, x = {}, 1
        while x <= 64 do
            local tone = row:sub(x, x)
            local finish = x + 1
            while finish <= 64 and row:sub(finish, finish) == tone do finish = finish + 1 end
            if tone ~= "." then
                local color = assert(colors[tone], "Invalid artwork palette: " .. name)
                local key = x .. ":" .. finish .. ":" .. tone
                local span = previous[key]
                if span then
                    span.h = span.h + 1
                else
                    span = { x = x - 1, y = y - 1, w = finish - x, h = 1, color = color }
                    spans[#spans + 1] = span
                end
                current[key] = span
            end
            x = finish
        end
        previous = current
    end
    colored_sprites[name] = spans
    return spans
end

local function draw_colored(draw_api, name, x, y, size, color, unavailable)
    local pixel = size / 64
    local alpha = color & 0xFF000000
    for _, span in ipairs(colored_sprite(name)) do
        draw_api.filled_rect(x + span.x * pixel, y + span.y * pixel,
            span.w * pixel, span.h * pixel, alpha | (unavailable and (color & 0xFFFFFF) or span.color))
    end
end

function Icons.monster(draw_api, name, x, y, size)
    draw_colored(draw_api, name or "unknown", x, y, size, 0xFFFFFFFF, false)
end

