local sprites = {}
for name, rows in pairs(artwork) do
    assert(#rows == 16, "Invalid icon height: " .. name)
    local spans = {}
    local previous = {}
    for y, row in ipairs(rows) do
        assert(#row == 16 and not row:find("[^.#+*]"), "Invalid icon row: " .. name)
        local current = {}
        local x = 1
        while x <= 16 do
            local tone = row:sub(x, x)
            local finish = x + 1
            while finish <= 16 and row:sub(finish, finish) == tone do finish = finish + 1 end
            if tone ~= "." then
                local key = x .. ":" .. finish .. ":" .. tone
                local span = previous[key]
                if span then
                    span.h = span.h + 1
                else
                    span = { x = x - 1, y = y - 1, w = finish - x, h = 1, tone = tone }
                    spans[#spans + 1] = span
                end
                current[key] = span
            end
            x = finish
        end
        previous = current
    end
    sprites[name] = spans
end

function Icons.draw(draw_api, name, x, y, size, color, unavailable)
    if artwork_palette[name] then
        draw_colored(draw_api, name, x, y, size, color, unavailable)
        return
    end
    local sprite = assert(sprites[name], "Unknown icon: " .. tostring(name))
    local alpha = color & 0xFF000000
    local palette = {
        ["#"] = alpha | 0x171717,
        ["+"] = color,
        ["*"] = unavailable and color or (alpha | 0xF2F2F2),
    }
    local pixel = size / 16
    for _, span in ipairs(sprite) do
        draw_api.filled_rect(x + span.x * pixel, y + span.y * pixel,
            span.w * pixel, span.h * pixel, palette[span.tone])
    end
end

return Icons
